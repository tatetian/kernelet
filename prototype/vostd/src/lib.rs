extern "Rust" {
    /// Generated by `#[ostd::main]` in the kernel proper.
    fn __ostd_main() -> !;
}

/// Whether the caller is in a bootstrap context, i.e. on a virtual CPU that has
/// no current task.
///
/// Real OSTD keeps an explicit flag that is cleared once boot is over. Here the
/// bootstrap context of a vCPU is exactly "no current task": the vCPU's own stack,
/// before it has switched to any OSTD task, and the idle loop it falls into.
#[inline]
pub(crate) fn in_bootstrap_context() -> bool {
    task::Task::current().is_none()
}

/// The kernelet's entry point, on virtual CPU 0.
///
/// # Safety
///
/// The caller must pass valid ABI tables and must call this exactly once.
pub(crate) unsafe extern "C" fn kernelet_entry(
    boot: *const abi::BootArgs,
    svc: *const abi::Services,
) {
    abi::init_tables(boot, svc);
    // A vCPU starts with its interrupts masked; the record can be found now,
    // so an upcall can be taken.
    task::preempt::cpu_local::set_irq_off(false);

    let args = &*boot;
    cpu::init(args.nr_vcpus as usize);
    time::init(args.tsc_khz);
    mm::frame::allocator::init(args.grant_paddr as usize, args.grant_len as usize);
    mm::heap::init();
    arch::cpu::context::init_fpu(args.fpu_area_size as usize);

    // The sandbox's command line, once the heap can hold it.
    let cmdline = if args.cmdline_ptr != 0 && args.cmdline_len != 0 {
        let bytes = core::slice::from_raw_parts(
            args.cmdline_ptr as *const u8,
            args.cmdline_len as usize,
        );
        core::str::from_utf8(bytes).unwrap_or("")
    } else {
        ""
    };
    boot::init(cmdline);

    crate::early_println!(
        "vOSTD up: grant {:#x}..{:#x}, linear map {:#x}, {} vCPU(s), tsc {} kHz, fpu area {} B",
        args.grant_paddr,
        args.grant_paddr + args.grant_len,
        args.linear_map_base,
        args.nr_vcpus,
        args.tsc_khz,
        args.fpu_area_size
    );
    if !cmdline.is_empty() {
        crate::early_println!("vOSTD: command line \"{}\"", cmdline);
    }
    mm::heap::report();

    __ostd_main()
}

/// The entry point of virtual CPU `id`, which the endovisor calls after the
/// kernel proper has asked for that vCPU to start.
///
/// # Safety
///
/// The caller must have entered the image at `kernelet_entry` on vCPU 0 first.
pub(crate) unsafe extern "C" fn vcpu_entry(id: u64) {
    // A vCPU starts with its interrupts masked; vCPU 0 has published the host
    // offsets, so this one's record can be found, and an upcall taken.
    task::preempt::cpu_local::set_irq_off(false);
    crate::early_println!("vOSTD: virtual CPU {} up", id);
    boot::smp::run_ap_entry();
    task::scheduler::vcpu_idle_loop()
}
